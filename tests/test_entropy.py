"""Tests for denoise entropy pre-flight diagnostic."""

from denoise.entropy import line_entropy, corpus_entropy, entropy_report


def test_line_entropy_empty():
    assert line_entropy("") == 0.0


def test_line_entropy_single_line():
    assert line_entropy("just one line") == 0.0


def test_line_entropy_all_identical():
    """All identical lines = 0 entropy (maximum redundancy)."""
    text = "\n".join(["same line"] * 100)
    assert line_entropy(text) == 0.0


def test_line_entropy_all_unique():
    """All unique lines = high entropy (no redundancy)."""
    text = "\n".join([f"unique line number {i}" for i in range(100)])
    ent = line_entropy(text)
    # log2(100) ≈ 6.64, should be close
    assert 6.0 < ent < 7.0


def test_line_entropy_mixed():
    """Mix of repeated and unique lines."""
    lines = ["repeated"] * 50 + [f"unique_{i}" for i in range(50)]
    text = "\n".join(lines)
    ent = line_entropy(text)
    # Should be between 0 (all same) and log2(51) ≈ 5.67 (all unique)
    assert 0.0 < ent < 6.0


def test_corpus_entropy_empty():
    result = corpus_entropy([])
    assert result["predicted_impact"] == "none"
    assert result["n_documents"] == 0


def test_corpus_entropy_high_redundancy():
    """Simulate Ansible-like logs: mostly repeated lines."""
    docs = []
    for _ in range(20):
        lines = ["ok: [host1]"] * 80 + [f"TASK [task_{i}]" for i in range(20)]
        docs.append("\n".join(lines))

    result = corpus_entropy(docs)
    assert result["within_doc_redundancy"] > 0.5
    assert result["predicted_impact"] in ("high", "medium")


def test_corpus_entropy_no_redundancy():
    """Simulate clean documents: all unique content."""
    docs = [
        "\n".join([f"document {d} line {i} with unique content xyz{d*100+i}"
                   for i in range(50)])
        for d in range(20)
    ]
    result = corpus_entropy(docs)
    assert result["within_doc_redundancy"] < 0.05
    assert result["predicted_impact"] in ("low", "none")


def test_corpus_entropy_cross_doc_repetition():
    """Shared boilerplate across documents raises cross-doc repetition."""
    header = "Copyright 2026 Acme Corp. All rights reserved."
    footer = "End of report. Generated by automated system."
    docs = []
    for d in range(20):
        lines = [header] + [f"unique content for doc {d} line {i}" for i in range(20)] + [footer]
        docs.append("\n".join(lines))

    result = corpus_entropy(docs)
    assert result["cross_doc_repetition_rate"] > 0.0


def test_corpus_entropy_single_doc():
    result = corpus_entropy(["line a\nline b\nline c"])
    assert result["n_documents"] == 1
    assert result["cross_doc_repetition_rate"] == 0.0


def test_entropy_report_format():
    docs = ["\n".join(["repeated"] * 50) for _ in range(5)]
    report = entropy_report(docs)
    assert "Entropy Pre-flight Report" in report
    assert "Predicted impact:" in report
    assert "5 documents" in report


def test_impact_thresholds():
    """Verify impact categories map correctly."""
    # Build a corpus with known redundancy levels
    # High: 90% repeated lines
    high_docs = ["\n".join(["same"] * 90 + [f"u{i}" for i in range(10)]) for _ in range(10)]
    assert corpus_entropy(high_docs)["predicted_impact"] == "high"

    # None: all unique
    none_docs = ["\n".join([f"d{d}l{i}" for i in range(100)]) for d in range(10)]
    assert corpus_entropy(none_docs)["predicted_impact"] == "none"
